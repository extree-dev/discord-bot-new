// ideaChannelId — ID канала ideaQueue/ (отдельная витрина идей по
// прямому сообщению, см. ideaQueue/config.js channelId), опционален:
// вызывающий код сам решает, стоит ли его передавать (например, /rules
// и scripts/setup-rules.js подтягивают его из ideaQueue.getConfig()).
// Без него — строка про идеи остаётся статичной (только кнопка).
// Канал подставляется упоминанием <#id>, а не именем — Discord сам
// рендерит его актуальным названием канала.
function buildRulesMessage(ideaChannelId) {
    const containers = buildSections(ideaChannelId).map(({ color, text }) =>
        baseContainer(color).addTextDisplayComponents(textDisplay(text))
    );
    return toMessage(...containers);
}

// Весь текст правил одной строкой — только для проверок формата в
// тестах (заголовки есть, эмодзи нет); сама отправка всегда идёт через
// buildRulesMessage(), а не через этот текст напрямую.
function getAllRulesText(ideaChannelId) {
    return buildSections(ideaChannelId)
        .map(s => s.text)
        .join('\n\n');
}

module.exports = { buildRulesMessage, getAllRulesText };
