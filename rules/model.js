// Доменный слой правил сервера. По фидбэку администратора — сначала
// один сплошной embed одним цветом читался как стена текста, затем
// версия с отдельной карточкой под каждую тему (7 карточек) оказалась
// слишком пёстрой. Утверждённый макет (вариант "C" — см. обсуждение в
// сессии): две смысловые карточки с нумерованными подразделами ("01 ·
// Заголовок") внутри вместо отдельной карточки на каждую тему, и
// отдельная красная карточка только для редкого/тревожного
// (экстренная блокировка) — она не должна теряться среди всего
// остального. Текст — официальная Markdown-разметка Discord (#, ##,
// ### и subtext через "-# "), без эмодзи. И /rules, и
// scripts/setup-rules.js показывают ровно это — редактировать правила
// нужно только тут.
const { COLORS } = require('../utils/embeds');
const { baseContainer, textDisplay, toMessage } = require('../utils/components');

const IDEA_SUBMIT_LINE_STATIC = '-# Идеи по улучшению сервера — через систему предложений (кнопка «Предложить идею»).';

function buildIdeaSubmitLine(ideaChannelId) {
    return ideaChannelId
        ? `-# Идеи по улучшению сервера — через кнопку «Предложить идею» или прямым сообщением в <#${ideaChannelId}> (оно сразу уходит на проверку модерации).`
        : IDEA_SUBMIT_LINE_STATIC;
}

// Три карточки (вместо прежних семи): синяя — всё спокойное и общее
