// Доменный слой правил сервера. По фидбэку администратора — один
// сплошной embed одним цветом читался как стена серого текста, без
// визуального разделения на темы. Теперь это несколько карточек
// Components V2 (тот же "дизайн-язык", что у тикетов/админ-панели/
// voice/suggestions — см. utils/components.js), каждая со своим
// акцентным цветом по смыслу секции: это и разбивает текст на
// отдельные блоки визуально, и помогает глазом быстро найти нужную
// тему. Текст внутри каждой карточки — официальная Markdown-разметка
// Discord (#, ##, ### и subtext через "-# "), без эмодзи. И /rules, и
// scripts/setup-rules.js показывают ровно это — редактировать правила
// нужно только тут.
const { COLORS } = require('../utils/embeds');
const { baseContainer, textDisplay, toMessage } = require('../utils/components');

const IDEA_SUBMIT_LINE_STATIC = '-# Идеи по улучшению сервера — через систему предложений (кнопка «Предложить идею»).';

function buildIdeaSubmitLine(ideaChannelId) {
    return ideaChannelId
        ? `-# Идеи по улучшению сервера — через кнопку «Предложить идею» или прямым сообщением в <#${ideaChannelId}> (оно сразу уходит на проверку модерации).`
        : IDEA_SUBMIT_LINE_STATIC;
}

